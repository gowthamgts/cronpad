// Derives client-side validation constants from api/openapi.yaml so the forms
// enforce the same limits as the server contract. Run via `just generate`.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const spec = parse(readFileSync(fileURLToPath(new URL("../../api/openapi.yaml", import.meta.url)), "utf8"));
const schemas = spec.components.schemas;
const params = spec.components.parameters;

function need(value, what) {
  if (value === undefined || value === null) throw new Error(`openapi.yaml is missing ${what}`);
  return value;
}

const rules = {
  jobNameMax: need(schemas.JobInput.properties.name.maxLength, "JobInput.name.maxLength"),
  jobNameMin: need(schemas.JobInput.properties.name.minLength, "JobInput.name.minLength"),
  jobDescriptionMax: need(schemas.JobInput.properties.description.maxLength, "JobInput.description.maxLength"),
  tagsMax: need(schemas.JobInput.properties.tags.maxItems, "JobInput.tags.maxItems"),
  scheduleExprMax: need(schemas.ScheduleInput.properties.expr.maxLength, "ScheduleInput.expr.maxLength"),
  previewCountMax: need(schemas.ScheduleInput.properties.count.maximum, "ScheduleInput.count.maximum"),
  retryAttemptsMin: need(schemas.Retry.properties.max_attempts.minimum, "Retry.max_attempts.minimum"),
  retryMultiplierMin: need(schemas.Retry.properties.multiplier.minimum, "Retry.multiplier.minimum"),
  retryJitterMax: need(schemas.Retry.properties.jitter.maximum, "Retry.jitter.maximum"),
  autoDisableMin: need(schemas.JobInput.properties.auto_disable_threshold.minimum, "auto_disable_threshold.minimum"),
  secretNamePattern: need(params.name.schema.pattern, "parameters.name.pattern"),
  secretValueMaxBytes: Number(/(\d+) UTF-8 bytes/.exec(need(schemas.SecretInput.properties.value.description, "SecretInput.value.description"))?.[1]),
  keyNameMax: need(schemas.KeyInput.properties.name.maxLength, "KeyInput.name.maxLength"),
  keyScopes: need(schemas.KeyInput.properties.scopes.items.enum, "KeyInput.scopes.enum"),
  workspaceNameMax: need(schemas.WorkspacePatch.properties.name.maxLength, "WorkspacePatch.name.maxLength"),
  alertNameMax: need(schemas.AlertRuleInput.properties.name.maxLength, "AlertRuleInput.name.maxLength"),
  alertEvents: need(schemas.AlertEvent.enum, "AlertEvent.enum"),
  misfirePolicies: need(schemas.JobInput.properties.misfire_policy.enum, "misfire_policy.enum"),
  overlapPolicies: need(schemas.JobInput.properties.overlap_policy.enum, "overlap_policy.enum"),
  pageLimitMax: need(params.limit.schema.maximum, "parameters.limit.maximum"),
};
if (!Number.isFinite(rules.secretValueMaxBytes)) throw new Error("cannot read the secret value limit from openapi.yaml");

const body = `// Code generated by scripts/gen-rules.mjs from api/openapi.yaml. DO NOT EDIT.
export const rules = ${JSON.stringify(rules, null, 2)} as const;
`;
writeFileSync(fileURLToPath(new URL("../src/api/rules.ts", import.meta.url)), body);
